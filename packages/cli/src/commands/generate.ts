/**
 * Generate command - generates types and client from schema
 *
 * Issue #22, #23 (watch mode), #24 (client package), #133 (project-local output)
 */

import { Command } from 'commander'
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs'
import { resolve, dirname, basename, join, relative, isAbsolute, sep } from 'path'
import { watch } from 'chokidar'
import { parseSchema } from '../parser/schema-parser.js'
import { toError } from '../utils/errors.js'
import { generateTypes } from '../generator/types-generator.js'
import { generateClient } from '../generator/client-generator.js'
import { generateClientPackage } from '../generator/client-package-generator.js'
import { loadConfig, type GSQConfig } from './init.js'

// =============================================================================
// Constants
// =============================================================================

/** Default schema file, used when neither a flag nor config provides one. */
export const DEFAULT_SCHEMA_FILE = 'schema.gsq.yaml'

/** Default output directory for types/client/index. */
export const DEFAULT_OUTPUT_DIR = 'generated'

/** Sub-directory of the output directory used for the typed client. */
export const DEFAULT_CLIENT_SUBDIR = 'client'

/** Marker that identifies a file as previously generated by gsquery. */
const GENERATED_MARKER = 'Auto-generated by gsquery'

/** Files written by the generator into a target directory. */
const GENERATED_FILENAMES = ['types.ts', 'client.ts', 'index.ts'] as const

// =============================================================================
// Types
// =============================================================================

/**
 * Raw options as parsed from the command line. Every value is optional so it
 * can fall back to gsquery.config.json and then to the built-in defaults.
 */
export interface GenerateCliOptions {
  schema?: string
  output?: string
  clientOutput?: string
  watch?: boolean
  client?: boolean
  force?: boolean
}

export interface GenerateOptions {
  schema: string
  output: string
  /** Typed client output directory. Defaults to `<output>/client`. */
  clientOutput?: string
  watch?: boolean
  client?: boolean
  /** Overwrite files that lack the auto-generated header. */
  force?: boolean
}

export interface GenerateResult {
  success: boolean
  files: string[]
  errors: string[]
  warnings: string[]
}

// =============================================================================
// Option Resolution
// =============================================================================

/**
 * Pick the first non-empty string, or undefined when there is none.
 */
function firstNonEmpty(...values: Array<string | undefined>): string | undefined {
  for (const value of values) {
    if (typeof value === 'string' && value.length > 0) {
      return value
    }
  }
  return undefined
}

/**
 * Resolve generate options from CLI flags, config file, and defaults.
 *
 * Precedence: CLI flag > gsquery.config.json > built-in default.
 */
export function resolveGenerateOptions(
  options: GenerateCliOptions,
  config: GSQConfig | null
): GenerateOptions {
  const schema = firstNonEmpty(options.schema, config?.schemaFile) ?? DEFAULT_SCHEMA_FILE
  const output = firstNonEmpty(options.output, config?.generatedDir) ?? DEFAULT_OUTPUT_DIR
  const clientOutput =
    firstNonEmpty(options.clientOutput, config?.clientDir) ?? join(output, DEFAULT_CLIENT_SUBDIR)

  return {
    schema,
    output,
    clientOutput,
    watch: options.watch,
    client: options.client,
    force: options.force,
  }
}

// =============================================================================
// Index Generator
// =============================================================================

/**
 * Generate index.ts that re-exports types and client
 */
export function generateIndex(): string {
  const lines = [
    '// Auto-generated by gsquery - DO NOT EDIT',
    '',
    "export * from './types.js'",
    "export * from './client.js'",
  ]
  return lines.join('\n') + '\n'
}

// =============================================================================
// File Operations
// =============================================================================

/**
 * Ensure directory exists
 */
function ensureDir(dirPath: string): void {
  if (!existsSync(dirPath)) {
    mkdirSync(dirPath, { recursive: true })
  }
}

/**
 * Write file with directory creation
 */
function writeFile(filePath: string, content: string): void {
  ensureDir(dirname(filePath))
  writeFileSync(filePath, content, 'utf-8')
}

/**
 * Check whether an existing file carries the gsquery auto-generated header.
 * Unreadable files are treated as not generated so they stay protected.
 */
function isGeneratedFile(filePath: string): boolean {
  try {
    return readFileSync(filePath, 'utf-8').includes(GENERATED_MARKER)
  } catch {
    return false
  }
}

/**
 * Collect existing target files that were not produced by gsquery.
 * These must not be overwritten unless --force is passed.
 */
function findProtectedFiles(targets: string[]): string[] {
  return targets.filter(target => existsSync(target) && !isGeneratedFile(target))
}

/**
 * Absolute paths of every file the generator writes into a directory.
 */
function targetPaths(dir: string): string[] {
  return GENERATED_FILENAMES.map(name => resolve(dir, name))
}

/**
 * Format a path for display and for the generated import example:
 * project-relative with POSIX separators, prefixed with './'.
 */
function toProjectPath(absolutePath: string): string {
  const rel = relative(process.cwd(), absolutePath)
  if (rel === '' || isAbsolute(rel)) {
    return absolutePath
  }
  return rel.split(sep).join('/')
}

/**
 * Import specifier the generated docs should show for the client directory.
 */
function toImportSpecifier(absolutePath: string): string {
  const projectPath = toProjectPath(absolutePath)
  if (isAbsolute(projectPath) || projectPath.startsWith('.')) {
    return projectPath
  }
  return `./${projectPath}`
}

