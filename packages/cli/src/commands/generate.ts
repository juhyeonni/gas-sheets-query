// Generate Logic
// =============================================================================

/**
 * Run the generate command
 */
export async function runGenerate(options: GenerateOptions): Promise<GenerateResult> {
  const errors: string[] = []
  const warnings: string[] = []
  const files: string[] = []
  
  // Resolve paths
  const schemaPath = resolve(process.cwd(), options.schema)
  const outputDir = resolve(process.cwd(), options.output)
  const clientOutputDir = resolve(
    process.cwd(),
    options.clientOutput ?? join(options.output, DEFAULT_CLIENT_SUBDIR)
  )

  // Check schema file exists
  if (!existsSync(schemaPath)) {
    return {
      success: false,
      files: [],
      errors: [`Schema file not found: ${schemaPath}`],
      warnings: [],
    }
  }
  
  // Read schema file
  let schemaContent: string
  try {
    schemaContent = readFileSync(schemaPath, 'utf-8')
  } catch (err) {
    const error = toError(err)
    return {
      success: false,
      files: [],
      errors: [`Failed to read schema file: ${error.message}`],
      warnings: [],
    }
  }
  
  // Parse schema
  const parseResult = parseSchema(schemaContent)
  
  if (!parseResult.success || !parseResult.schema) {
    return {
      success: false,
      files: [],
      errors: parseResult.errors.map(e => e.message),
      warnings: [],
    }
  }
  
  // Collect parse warnings
  if (parseResult.errors.length > 0) {
    for (const err of parseResult.errors) {
      warnings.push(err.message)
    }
  }
  
  const schema = parseResult.schema

  // Refuse to clobber files that gsquery did not generate
  if (!options.force) {
    const candidates = [
      ...targetPaths(outputDir),
      ...(options.client ? targetPaths(clientOutputDir) : []),
    ]
    const protectedFiles = findProtectedFiles(candidates)

    if (protectedFiles.length > 0) {
      return {
        success: false,
        files: [],
        errors: protectedFiles.map(
          file =>
            `Refusing to overwrite ${toProjectPath(file)}: it is missing the ` +
            `"${GENERATED_MARKER}" header. Use --force to overwrite.`
        ),
        warnings,
      }
    }
  }

  // Generate types
  try {
    const typesContent = generateTypes(schema)
    const typesPath = resolve(outputDir, 'types.ts')
    writeFile(typesPath, typesContent)
    files.push('types.ts')
  } catch (err) {
    const error = toError(err)
    return {
      success: false,
      files,
      errors: [...errors, `Failed to generate types: ${error.message}`],
      warnings,
    }
  }
  
  // Generate client
  try {
    const clientContent = generateClient(schema)
    const clientPath = resolve(outputDir, 'client.ts')
    writeFile(clientPath, clientContent)
    files.push('client.ts')
  } catch (err) {
    const error = toError(err)
    return {
      success: false,
      files,
      errors: [...errors, `Failed to generate client: ${error.message}`],
      warnings,
    }
  }
  
  // Generate index
  try {
    const indexContent = generateIndex()
    const indexPath = resolve(outputDir, 'index.ts')
    writeFile(indexPath, indexContent)
    files.push('index.ts')
  } catch (err) {
    const error = toError(err)
    return {
      success: false,
      files,
      errors: [...errors, `Failed to generate index: ${error.message}`],
      warnings,
    }
  }
  
  // Generate typed client into the project (--client option)
  if (options.client) {
    try {
      const clientFiles = generateClientPackage(schema, {
        importPath: toImportSpecifier(clientOutputDir),
      })

      for (const [filename, content] of Object.entries(clientFiles)) {
        writeFile(resolve(clientOutputDir, filename), content)
      }
      files.push(toProjectPath(clientOutputDir))
    } catch (err) {
      const error = toError(err)
      return {
        success: false,
        files,
        errors: [...errors, `Failed to generate client: ${error.message}`],
        warnings,
      }
    }
  }

  return {
    success: true,
    files,
    errors,
    warnings,
  }
}

