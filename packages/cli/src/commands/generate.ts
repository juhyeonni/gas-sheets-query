/**
 * Format current time as [HH:MM:SS]
 */
function formatTimestamp(): string {
  const now = new Date()
  const hours = String(now.getHours()).padStart(2, '0')
  const minutes = String(now.getMinutes()).padStart(2, '0')
  const seconds = String(now.getSeconds()).padStart(2, '0')
  return `[${hours}:${minutes}:${seconds}]`
}

/**
 * Run generate and print results (used by both initial run and watch)
 */
async function runAndPrint(options: GenerateOptions): Promise<boolean> {
  const result = await runGenerate(options)
  
  if (!result.success) {
    console.error('❌ Generation failed:')
    for (const error of result.errors) {
      console.error(`   ${error}`)
    }
    return false
  }
  
  // Show warnings if any
  if (result.warnings.length > 0) {
    console.log('⚠️  Warnings:')
    for (const warning of result.warnings) {
      console.log(`   ${warning}`)
    }
  }
  
  console.log(`✅ Generated ${result.files.join(', ')}`)
  return true
}

/**
 * Start watching schema file for changes
 */
async function startWatch(options: GenerateOptions): Promise<void> {
  const schemaPath = resolve(process.cwd(), options.schema)
  const schemaName = basename(schemaPath)
  
  console.log('👀 Watching for changes...')
  console.log('')
  
  const watcher = watch(schemaPath, {
    persistent: true,
    ignoreInitial: true,
  })
  
  // Debounce to avoid multiple rapid triggers
  let debounceTimer: NodeJS.Timeout | null = null
  
  watcher.on('change', () => {
    if (debounceTimer) {
      clearTimeout(debounceTimer)
    }
    
    debounceTimer = setTimeout(async () => {
      const startTime = performance.now()
      console.log(`${formatTimestamp()} ${schemaName} changed`)
      
      try {
        const success = await runAndPrint(options)
        const elapsed = Math.round(performance.now() - startTime)
        
        if (success) {
          console.log(`   Regenerated in ${elapsed}ms`)
        }
      } catch (err) {
        const error = toError(err)
        console.error(`❌ Error: ${error.message}`)
      }
      console.log('')
    }, 100) // 100ms debounce
  })
  
  watcher.on('error', (err: unknown) => {
    const error = err instanceof Error ? err : new Error(String(err))
    console.error(`❌ Watcher error: ${error.message}`)
  })
  
  // Handle Ctrl+C gracefully
  const cleanup = () => {
    console.log('')
    console.log('👋 Stopping watch mode...')
    watcher.close()
    process.exit(0)
  }
  
  process.on('SIGINT', cleanup)
  process.on('SIGTERM', cleanup)
  
  // Keep process alive
  await new Promise(() => {})
}

// =============================================================================
// CLI Command
// =============================================================================

export const generateCommand = new Command('generate')
  .description('Generate types and client from schema')
  .option('-s, --schema <path>', `Schema file path (default: ${DEFAULT_SCHEMA_FILE})`)
  .option('-o, --output <path>', `Output directory (default: ${DEFAULT_OUTPUT_DIR})`)
  .option('-w, --watch', 'Watch schema file for changes and regenerate')
  .option('-c, --client', 'Also generate a typed client into the project')
  .option(
    '--client-output <path>',
    `Typed client output directory (default: <output>/${DEFAULT_CLIENT_SUBDIR})`
  )
  .option('-f, --force', 'Overwrite files that lack the auto-generated header')
  .action(async (cliOptions: GenerateCliOptions) => {
    let config: GSQConfig | null = null
    try {
      config = loadConfig()
    } catch (err) {
      console.warn(`⚠️  ${toError(err).message}`)
    }

    const options = resolveGenerateOptions(cliOptions, config)

    console.log('🔧 Generating from schema...')
    console.log(`   Schema: ${options.schema}`)
    console.log(`   Output: ${options.output}`)
    if (options.client) {
      console.log(`   Client: ${options.clientOutput}`)
    }
    console.log('')

    // Initial generation
    const success = await runAndPrint(options)
    
    if (!success && !options.watch) {
      process.exit(1)
    }
    
    // Watch mode
    if (options.watch) {
      console.log('')
      await startWatch(options)
    } else {
      console.log('')
      console.log('🎉 Done!')
    }
  })
